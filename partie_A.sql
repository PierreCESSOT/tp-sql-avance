CREATE MATERIALIZED VIEW mv_synthese_segments AS
SELECT cl.segment,
       COUNT(co.id) AS nb_commandes,
       ROUND(SUM(co.montant_total), 2) AS ca_total
FROM commandes co
JOIN clients cl ON cl.id = co.client_id
GROUP BY cl.segment;

