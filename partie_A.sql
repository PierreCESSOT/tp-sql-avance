CREATE INDEX idx_commandes_statut_date ON commandes (statut, date_commande);

CREATE TABLE commandes_part (
    id            INT GENERATED BY DEFAULT AS IDENTITY,
    client_id     INT NOT NULL,
    date_commande DATE NOT NULL,
    statut        VARCHAR(20),
    canal         VARCHAR(20),
    montant_total NUMERIC(12, 2),
    PRIMARY KEY (id, date_commande)
) PARTITION BY RANGE (date_commande);

CREATE TABLE commandes_2024 PARTITION OF commandes_part
    FOR VALUES FROM ('2024-01-01') TO ('2025-01-01');
CREATE TABLE commandes_2025 PARTITION OF commandes_part
    FOR VALUES FROM ('2025-01-01') TO ('2026-01-01');
CREATE TABLE commandes_2026 PARTITION OF commandes_part
    FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');

INSERT INTO commandes_part (id, client_id, date_commande, statut, canal, montant_total)
SELECT id, client_id, date_commande, statut, canal, montant_total
FROM commandes;

CREATE INDEX idx_cmdpart_statut_date ON commandes_part (statut, date_commande);

EXPLAIN ANALYZE
SELECT id, client_id, date_commande, montant_total
FROM commandes_part
WHERE date_commande >= '2026-01-01'
  AND date_commande <  '2027-01-01'
  AND statut = 'LIVREE'
ORDER BY montant_total DESC
LIMIT 10;

-- Effet du Partition Pruning :
-- Le moteur n'ouvre que la partition commandes_2026 et ignore commandes_2024 et
-- commandes_2025 (elles n'apparaissent pas dans le plan). On lit environ 1/3 des données
-- au lieu de 3/3. Sur seulement 240 lignes, les temps restent minuscules ; le bénéfice
-- devient important sur de gros volumes.

